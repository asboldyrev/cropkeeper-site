                <h2>8. Экспорт данных и удаление аккаунта</h2>
                <p>Перед удалением аккаунта вы можете запросить архив своих пользовательских данных. В архив могут входить данные об огороде, выбранном населённом пункте, растениях, семенах, задачах, событиях, журнале и другие пользовательские данные, необходимые для последующего восстановления.</p>
                <p>Email и пароль в пользовательский экспортный архив не включаются.</p>
                <p>Готовый архив хранится на сервере 48 часов с момента формирования. По вашему выбору ссылка на скачивание может быть отправлена на email.</p>
                <p>Если после формирования архива вы удалите аккаунт, уже созданный архив может оставаться доступным до первоначального окончания этих 48 часов. Удаление аккаунта не продлевает срок хранения. После истечения срока серверная копия уничтожается автоматически.</p>
                <p>После скачивания архива вы самостоятельно отвечаете за безопасное хранение полученной копии.</p>
                <p>При новой регистрации ранее скачанный архив можно использовать для восстановления пользовательских данных только в аккаунт, где ещё нет собственных растений, семян, задач, записей журнала и других данных, которые мешают однозначному импорту.</p>
