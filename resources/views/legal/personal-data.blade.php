                <h2>4. Погода и Open-Meteo</h2>
                <p>Если вы выбрали населённый пункт, Cropkeeper использует его приблизительные координаты, чтобы получить погодные данные через Open-Meteo.</p>
                <p>В Open-Meteo передаются только координаты населённого пункта. Email, ID вашего аккаунта и содержимое пользовательских записей вместе с таким запросом не передаются.</p>
            </section>

