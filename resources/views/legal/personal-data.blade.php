                <h2>5. Оплата и платёжный провайдер</h2>
                <p>Платёжные реквизиты банковской карты вводятся на стороне платёжного провайдера. Cropkeeper не хранит полный номер карты и CVC.</p>
                <p>Для работы платного доступа Cropkeeper может получать и хранить служебные сведения о платеже: сумму, дату, идентификатор и статус операции, выбранный тариф и период, а также технический токен, если он нужен для разрешённого вами автопродления.</p>
                <p>После отключения автопродления соответствующая платёжная привязка больше не используется для новых автоматических списаний.</p>
