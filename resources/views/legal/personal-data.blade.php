                <h2>9. Сроки хранения и удаление</h2>
                <p>Данные аккаунта и пользовательский контент хранятся пока это необходимо для работы вашего аккаунта и исполнения условий сервиса. При окончательном удалении аккаунта активные пользовательские данные удаляются, кроме сведений, которые необходимо сохранить на самостоятельном законном основании.</p>
                <p>Финансовые и иные юридически значимые сведения могут храниться в сроки, необходимые для учёта, подтверждения расчётов и защиты законных требований.</p>
                <p>Технические IP/user-agent и системные журналы хранятся в пределах фактических сроков хранения, предоставляемых и настроенных у используемой хостинговой инфраструктуры, и не должны сохраняться дольше, чем это необходимо для безопасности и диагностики.</p>
                <p>Временный экспортный архив хранится не более 48 часов с момента готовности, как описано выше.</p>
